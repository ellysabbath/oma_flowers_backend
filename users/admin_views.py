class AdminUserSetRoleView(APIView):
    """
    POST /api/v1/admin/users/<id>/set-role/
    body: { user_type: 'admin' | 'distributor' | 'customer' }
    """
    # permission_classes = [IsAdminUser]

    ALLOWED = {"admin", "distributor", "customer"}

    def post(self, request, pk):
        user = get_object_or_404(User, pk=pk)
        user_type = str(request.data.get("user_type", "")).lower()
        if user_type not in self.ALLOWED:
            return _error(f"user_type must be one of {sorted(self.ALLOWED)}.")

        if _is_self(request, user) and user_type != "admin":
            return _error(
                "You cannot demote your own admin account.",
                status.HTTP_403_FORBIDDEN,
            )

        changed = user.user_type != user_type
        user.user_type = user_type
        if user_type == "admin":
            user.is_staff = True
        elif not user.is_superuser:
            user.is_staff = False
        user.save(update_fields=["user_type", "is_staff"])

        if changed:
            notify_role_changed(user, user_type)

        return Response(_serialize(user))


