class AdminUserSetPasswordView(APIView):
    """
    POST /api/v1/admin/users/<id>/set-password/   body: { password }

    Sets a new password and sends it to the user via SMS so they can
    log in immediately. If SMS delivery fails, the response still
    reports success (password did change) but flags `sms_sent: false`
    so the admin knows to share it manually.
    """
    # permission_classes = [IsAdminUser]

    def post(self, request, pk):
        user = get_object_or_404(User, pk=pk)

        password = request.data.get("password")
        if not password:
            return _error("password is required.")
        if len(str(password)) < 6:
            return _error("password must be at least 6 characters.")

        user.set_password(password)
        user.save(update_fields=["password"])

        # SMS the new password so the user can log in right away.
        sms_sent = notify_password_reset_by_admin(user, password)

        return Response({
            "detail": (
                "Password updated and sent via SMS."
                if sms_sent
                else "Password updated, but SMS could not be delivered. "
                     "Please share the new password with the user directly."
            ),
            "sms_sent": bool(sms_sent),
        })


