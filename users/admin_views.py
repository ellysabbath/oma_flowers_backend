class AdminUserListCreateView(APIView):
    """
    GET  /api/v1/admin/users/     → paginated list of all users
    POST /api/v1/admin/users/     → create a user
    """
    # permission_classes = [IsAdminUser]

    def get(self, request):
        qs = User.objects.all()
        qs = _apply_filters(qs, request)

        paginator = AdminUserPagination()
        page = paginator.paginate_queryset(qs, request, view=self)
        serializer = UserSerializer(page, many=True)
        return paginator.get_paginated_response(serializer.data)

    @transaction.atomic
    def post(self, request):
        data = request.data.copy()

        password = data.get("password")
        if not password:
            return _error("password is required.")

        data.setdefault("user_type", "customer")
        data.setdefault("status", "active")

        # If only `full_name` was sent, split it before serializing.
        if data.get("full_name") and not data.get("first_name"):
            parts = str(data["full_name"]).strip().split(" ", 1)
            data["first_name"] = parts[0]
            data["last_name"] = parts[1] if len(parts) > 1 else ""

        serializer = UserSerializer(data=data)
        if not serializer.is_valid():
            return Response(
                serializer.errors, status=status.HTTP_400_BAD_REQUEST
            )

        validated = dict(serializer.validated_data)
        validated.pop("password", None)
        validated.pop("password2", None)

        # create_user → hashed password + model save() → OMA user_id.
        user = User(**validated)
        user.set_password(password)

        explicit_type = str(data.get("user_type", "")).lower()
        if explicit_type in {"admin", "distributor", "customer"}:
            user.user_type = explicit_type
            if explicit_type == "admin":
                user.is_staff = True
        else:
            user.user_type = "customer"

        explicit_status = str(data.get("status", "")).lower()
        if explicit_status in {"active", "inactive", "pending", "banned"}:
            user.status = explicit_status
        else:
            user.status = "active"

        if explicit_status == "banned":
            user.is_active = False

        user.save()

        # Do NOT notify on creation — the notification flows are meant
        # for *admin-initiated changes* to existing users.

        return Response(_serialize(user), status=status.HTTP_201_CREATED)


