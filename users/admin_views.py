class AdminUserDetailView(APIView):
    """
    GET    /api/v1/admin/users/<id>/
    PATCH  /api/v1/admin/users/<id>/
    PUT    /api/v1/admin/users/<id>/
    DELETE /api/v1/admin/users/<id>/
    """
    # permission_classes = [IsAdminUser]

    def get_object(self, pk):
        return get_object_or_404(User, pk=pk)

    def get(self, request, pk):
        return Response(_serialize(self.get_object(pk)))

    def _apply_role_status_and_notify(self, user, explicit_type, explicit_status):
        """
        Write user_type / status (with the accompanying staff/active
        flags) and fire the correct SMS notifications. Returns the
        list of fields that were actually changed (for update_fields).
        """
        fields = []
        role_changed = False
        status_changed = False

        if explicit_type in {"admin", "distributor", "customer"}:
            if user.user_type != explicit_type:
                role_changed = True
            user.user_type = explicit_type
            if explicit_type == "admin":
                user.is_staff = True
            elif not user.is_superuser:
                user.is_staff = False
            fields += ["user_type", "is_staff"]

        if explicit_status in {"active", "inactive", "pending", "banned"}:
            if user.status != explicit_status:
                status_changed = True
            user.status = explicit_status
            if explicit_status == "banned":
                user.is_active = False
            elif explicit_status == "active":
                user.is_active = True
            fields += ["status", "is_active"]

        if fields:
            user.save(update_fields=list(set(fields)))

        # Fire SMS notifications only if something really changed.
        if role_changed and explicit_type:
            notify_role_changed(user, explicit_type)
        if status_changed and explicit_status:
            notify_status_changed(user, explicit_status)

        return fields

    @transaction.atomic
    def patch(self, request, pk):
        user = self.get_object(pk)
        data = request.data.copy()

        # Self-protection
        if _is_self(request, user):
            if "user_type" in data and data["user_type"] != "admin":
                return _error(
                    "You cannot demote your own admin account.",
                    status.HTTP_403_FORBIDDEN,
                )
            if data.get("status") == "banned":
                return _error(
                    "You cannot ban your own account.",
                    status.HTTP_403_FORBIDDEN,
                )

        # Pop read-only fields the serializer would reject
        explicit_type = data.pop("user_type", None)
        explicit_status = data.pop("status", None)

        serializer = UserSerializer(user, data=data, partial=True)
        if not serializer.is_valid():
            return Response(
                serializer.errors, status=status.HTTP_400_BAD_REQUEST
            )
        serializer.save()

        self._apply_role_status_and_notify(
            user, explicit_type, explicit_status
        )

        return Response(_serialize(user))

    @transaction.atomic
    def put(self, request, pk):
        user = self.get_object(pk)
        data = request.data.copy()

        if _is_self(request, user):
            if "user_type" in data and data["user_type"] != "admin":
                return _error(
                    "You cannot demote your own admin account.",
                    status.HTTP_403_FORBIDDEN,
                )
            if data.get("status") == "banned":
                return _error(
                    "You cannot ban your own account.",
                    status.HTTP_403_FORBIDDEN,
                )

        explicit_type = data.pop("user_type", None)
        explicit_status = data.pop("status", None)

        serializer = UserSerializer(user, data=data)
        if not serializer.is_valid():
            return Response(
                serializer.errors, status=status.HTTP_400_BAD_REQUEST
            )
        serializer.save()

        self._apply_role_status_and_notify(
            user, explicit_type, explicit_status
        )

        return Response(_serialize(user))

    def delete(self, request, pk):
        user = self.get_object(pk)

        if _is_self(request, user):
            return _error(
                "You cannot delete your own account.",
                status.HTTP_403_FORBIDDEN,
            )

        user.delete()
        return Response(status=status.HTTP_204_NO_CONTENT)


