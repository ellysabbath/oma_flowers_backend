# users/admin_views.py
"""
Admin-only CRUD for User records, with SMS notifications.

Endpoints (all under /api/v1/admin/users/):
    GET     /                          list all users (paginated, filterable)
    POST    /                          create user
    GET     /<id>/                     retrieve single user
    PATCH   /<id>/                     partial update
    PUT     /<id>/                     full update
    DELETE  /<id>/                     delete user

    POST    /<id>/set-password/        set a new password (SMSes the new one)
    POST    /<id>/activate/            reactivate account
    POST    /<id>/deactivate/          deactivate account
    POST    /<id>/ban/                 set status='banned'
    POST    /<id>/unban/               set status='active'
    POST    /<id>/verify-email/        mark email as verified

    POST    /<id>/make-admin/          promote to admin
    POST    /<id>/make-distributor/    promote to distributor
    POST    /<id>/make-customer/       demote to customer
    POST    /<id>/set-role/            generic role setter (body: user_type)

    GET     /stats/                    aggregated counts

Notes on the OMA `user_id` field:
- `user_id` is read-only everywhere on this API. It is generated by
  `User.save()` on first creation and must never be reassigned.
- The list/search endpoint can filter by `user_id` (exact) and search
  it as text (icontains).
- `<id>` in all URLs is the **numeric primary key** (`pk`), not the
  OMA `user_id`.

Notifications:
- Every action that changes a user's role or account state triggers
  a fire-and-forget SMS notification to that user. Failing to send
  never rolls back or fails the admin action — see `auth.utils`.
- Password changes are special: the SMS includes the new plaintext
  password so the user can log in immediately.
- "Self-protection" guards prevent an admin from demoting, banning,
  deactivating, or deleting their own account.

Auth:
- These views are open at the DRF layer so you can wire them behind
  whatever admin auth you use (session, JWT role, IP, etc.).
- Uncomment `permission_classes = [IsAdminUser]` in each view (or set
  a project-wide default) to let DRF enforce it too.
"""

