def _apply_filters(qs, request):
    """
    Apply querystring filters: user_type, status, email_verified,
    is_active, search (email/username/name/phone/user_id), ordering.
    """
    user_type = request.query_params.get("user_type")
    if user_type:
        qs = qs.filter(user_type=user_type)

    status_param = request.query_params.get("status")
    if status_param:
        qs = qs.filter(status=status_param)

    email_verified = request.query_params.get("email_verified")
    if email_verified is not None:
        qs = qs.filter(
            email_verified=str(email_verified).lower() in ("1", "true", "yes")
        )

    is_active = request.query_params.get("is_active")
    if is_active is not None:
        qs = qs.filter(
            is_active=str(is_active).lower() in ("1", "true", "yes")
        )

    user_id_exact = request.query_params.get("user_id")
    if user_id_exact:
        qs = qs.filter(user_id__iexact=user_id_exact)

    search = request.query_params.get("search")
    if search:
        qs = qs.filter(
            Q(user_id__icontains=search)
            | Q(email__icontains=search)
            | Q(username__icontains=search)
            | Q(first_name__icontains=search)
            | Q(last_name__icontains=search)
            | Q(phone__icontains=search)
        )

    ordering = request.query_params.get("ordering") or "-date_joined"
    allowed_ordering = {
        "date_joined", "-date_joined",
        "created_at", "-created_at",
        "email", "-email",
        "user_id", "-user_id",
        "user_type", "-user_type",
    }
    if ordering in allowed_ordering:
        qs = qs.order_by(ordering)

    return qs


def _error(message, code=status.HTTP_400_BAD_REQUEST):
    return Response({"detail": message}, status=code)


def _serialize(user):
    return UserSerializer(user).data


def _is_self(request, user) -> bool:
    """True if the authenticated request user is the same row."""
    return request.user.is_authenticated and request.user.pk == user.pk


